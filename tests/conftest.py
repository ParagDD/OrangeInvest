import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from harness import RESULTS  # noqa: E402


def pytest_sessionfinish(session, exitstatus):
    if not RESULTS:
        return
    out = Path(__file__).resolve().parents[1] / "reports"
    out.mkdir(exist_ok=True)
    rows = sorted(RESULTS, key=lambda r: r["name"])
    esc = lambda s: str(s).replace("|", "\\|").replace("\n", " ")
    lines = ["# Eval table (generated by `pytest`; do not edit by hand)", "",
             f"{sum(r['status'] == 'PASS' for r in rows)}/{len(rows)} scenarios passed.", "",
             "| # | Scenario | Expected | Actual | Result | Notes |", "|---|---|---|---|---|---|"]
    for i, r in enumerate(rows, 1):
        lines.append(f"| {i} | {esc(r['name'])} | {esc(r['expected'])} | {esc(r['actual'])} | {r['status']} | {esc(r['notes'])} |")
    (out / "eval_table.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    (out / "eval_results.json").write_text(json.dumps(rows, indent=2), encoding="utf-8")
